/** A signed figure: +12, −12 (minus sign, not a hyphen), 0. */
const signed = (n: number) => (n > 0 ? `+${n}` : n < 0 ? `−${-n}` : '0');
/** Genitive, after «длиннее»: «12 минут», «1 минуты». */
const minutesGen = (n: number) => `${n} ${plural(n, { one: 'минуты', few: 'минут', many: 'минут', other: 'минуты' })}`;
/** Accusative, after «через»: «30 минут», «1 минуту». */
const minutesAcc = (n: number) => `${n} ${plural(n, { one: 'минуту', few: 'минуты', many: 'минут', other: 'минуты' })}`;

